// ===== RENDER BLOG POSTS ON BLOG PAGE =====
function renderBlogPosts() {
    const blogGrid = document.getElementById('blogGrid');
    if (!blogGrid) return;

    blogPosts.forEach(post => {
        const card = document.createElement('div');
        card.className = 'blog-card';
        
        card.innerHTML = `
            <div class="blog-card-image">
                <img src="${post.image}" alt="${post.title}" />
                <span class="blog-category">${post.category}</span>
            </div>
            <div class="blog-card-content">
                <h3>${post.title}</h3>
                <p class="blog-excerpt">${post.excerpt}</p>
                <div class="blog-card-footer">
                    <span class="blog-date"><i class="far fa-calendar"></i> ${post.date}</span>
                </div>
            </div>
        `;
        
        blogGrid.appendChild(card);
    });
}

// ===== RENDER BLOG DETAIL PAGE =====
function renderBlogDetail() {
    const blogDetail = document.getElementById('blogDetail');
    if (!blogDetail) return;

    // Get blog ID from URL
    const urlParams = new URLSearchParams(window.location.search);
    const blogId = parseInt(urlParams.get('id')) || 1;

    // Find the blog post
    const post = blogPosts.find(p => p.id === blogId);
    if (!post) {
        blogDetail.innerHTML = '<p>Blog post not found.</p>';
        return;
    }

    // Render blog detail
    blogDetail.innerHTML = `
        <div class="blog-detail-header">
            <div class="blog-detail-image">
                <img src="${post.image}" alt="${post.title}" />
            </div>
            <div class="blog-detail-info">
                <span class="blog-category">${post.category}</span>
                <h1>${post.title}</h1>
                <div class="blog-detail-meta">
                    <span><i class="far fa-calendar"></i> ${post.date}</span>
                    <span><i class="far fa-clock"></i> 5 min read</span>
                </div>
            </div>
        </div>
        <div class="blog-detail-body">
            ${post.content}
        </div>
    `;

    // Render related posts
    renderRelatedPosts(blogId);
}

// ===== RENDER RELATED POSTS =====
function renderRelatedPosts(currentBlogId) {
    const relatedPostsContainer = document.getElementById('relatedPosts');
    if (!relatedPostsContainer) return;

    // Get 3 random posts (excluding current)
    const related = blogPosts
        .filter(post => post.id !== currentBlogId)
        .sort(() => Math.random() - 0.5)
        .slice(0, 3);

    related.forEach(post => {
        const card = document.createElement('div');
        card.className = 'related-post-card';
        
        card.innerHTML = `
            <div class="related-post-image">
                <img src="${post.image}" alt="${post.title}" />
            </div>
            <div class="related-post-content">
                <h4>${post.title}</h4>
                <p>${post.excerpt.substring(0, 80)}...</p>
            </div>
        `;
        
        relatedPostsContainer.appendChild(card);
    });
}

// ===== HAMBURGER MENU =====
const hamburger = document.querySelector('.hamburger');
const navLinks = document.querySelector('.nav-links');

if (hamburger) {
    hamburger.addEventListener('click', () => {
        hamburger.classList.toggle('active');
        navLinks.classList.toggle('active');
    });

    // Close menu when a link is clicked
    document.querySelectorAll('.nav-links a').forEach(link => {
        link.addEventListener('click', () => {
            hamburger.classList.remove('active');
            navLinks.classList.remove('active');
        });
    });
}

// ===== INITIALIZE PAGE =====
document.addEventListener('DOMContentLoaded', () => {
    // Check if we're on blog page or detail page
    if (document.getElementById('blogGrid')) {
        renderBlogPosts();
    } else if (document.getElementById('blogDetail')) {
        renderBlogDetail();
    }

    // Apply reveal animations
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, observerOptions);

    // Observe all blog cards
    document.querySelectorAll('.blog-card, .related-post-card').forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
        observer.observe(el);
    });
});

